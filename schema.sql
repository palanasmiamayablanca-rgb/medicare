CREATE DATABASE IF NOT EXISTS medicare_study CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE medicare_study;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('patient','caregiver','admin') NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS caregiver_links (
 patient_id INT UNSIGNED NOT NULL,
 caregiver_id INT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(patient_id, caregiver_id),
 FOREIGN KEY(patient_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(caregiver_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS medications (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 patient_id INT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL,
 dosage VARCHAR(100) NOT NULL,
 scheduled_time TIME NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(patient_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS doses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 medication_id INT UNSIGNED NOT NULL,
 patient_id INT UNSIGNED NOT NULL,
 scheduled_at DATETIME NOT NULL,
 status ENUM('pending','taken','missed') NOT NULL DEFAULT 'pending',
 responded_at DATETIME NULL,
 UNIQUE KEY unique_med_schedule(medication_id,scheduled_at),
 KEY patient_schedule(patient_id,scheduled_at),
 FOREIGN KEY(medication_id) REFERENCES medications(id) ON DELETE CASCADE,
 FOREIGN KEY(patient_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 recipient_id INT UNSIGNED NOT NULL,
 dose_id BIGINT UNSIGNED NOT NULL,
 message VARCHAR(255) NOT NULL,
 is_read TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY notification_once(recipient_id,dose_id),
 FOREIGN KEY(recipient_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(dose_id) REFERENCES doses(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activity_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NULL,
 event VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
